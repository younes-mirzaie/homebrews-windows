# Builds Retrogram (Release|ARM .xap) with Visual Studio 2015 + the Windows Phone 8.1 SDK.
#
# The Telegram api_id / api_hash are never stored in git. This script reads them from
#   1. the TG_API_ID and TG_API_HASH environment variables (the GitHub Actions workflow sets these
#      from repository secrets), or
#   2. retrogram\telegram-api.local (git-ignored), two lines: TG_API_ID=12345 and TG_API_HASH=abc...
# and writes app\MetroTelegram\AppConfig.Secrets.cs (also git-ignored) before building.
param(
    [string]$Configuration = "Release",
    [string]$Platform = "ARM"
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$app = Join-Path $root "app"
$proj = Join-Path $app "MetroTelegram"

# --- Telegram API credentials ---
$apiId = $env:TG_API_ID
$apiHash = $env:TG_API_HASH
$localFile = Join-Path $root "telegram-api.local"
if ((-not $apiId -or -not $apiHash) -and (Test-Path $localFile)) {
    foreach ($line in Get-Content $localFile) {
        if ($line -match '^\s*TG_API_ID\s*=\s*(\S+)') { $apiId = $Matches[1] }
        if ($line -match '^\s*TG_API_HASH\s*=\s*(\S+)') { $apiHash = $Matches[1] }
    }
}
if (-not $apiId -or -not $apiHash) {
    throw "Telegram API key missing. Set TG_API_ID and TG_API_HASH, or create retrogram\telegram-api.local (see README.md)."
}
$apiId = $apiId.Trim(); $apiHash = $apiHash.Trim()
if ($apiId -notmatch '^\d+$') { throw "TG_API_ID should be a number (from my.telegram.org)." }
if ($apiHash -notmatch '^[0-9a-fA-F]{32}$') { throw "TG_API_HASH should be 32 hex characters (from my.telegram.org)." }

$secrets = @"
// Generated by build.ps1. Never commit this file.
namespace MetroTelegram
{
    public static partial class AppConfig
    {
        public const int ApiId = $apiId;
        public const string ApiHash = "$apiHash";
    }
}
"@
Set-Content -Path (Join-Path $proj "AppConfig.Secrets.cs") -Value $secrets -Encoding UTF8

# --- NuGet restore ---
$tools = Join-Path $root ".tools"
$nuget = Join-Path $tools "nuget.exe"
if (-not (Test-Path $nuget)) {
    New-Item -ItemType Directory -Force -Path $tools | Out-Null
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest "https://dist.nuget.org/win-x86-commandline/v5.11.0/nuget.exe" -OutFile $nuget
}
& $nuget restore (Join-Path $app "MetroTelegram.sln") -PackagesDirectory (Join-Path $app "packages") -NonInteractive
if ($LASTEXITCODE -ne 0) { throw "NuGet restore failed." }

# --- Build ---
$msbuild = Join-Path ${env:ProgramFiles(x86)} "MSBuild\14.0\Bin\MSBuild.exe"
if (-not (Test-Path $msbuild)) { throw "MSBuild 14.0 (Visual Studio 2015) not found at $msbuild." }
& $msbuild (Join-Path $app "MetroTelegram.sln") /m /nologo /v:minimal "/p:Configuration=$Configuration" "/p:Platform=$Platform"
if ($LASTEXITCODE -ne 0) { throw "Build failed." }

$xap = Get-ChildItem -Path (Join-Path $proj "Bin") -Recurse -Filter "Retrogram_*.xap" | Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $xap) { throw "Build finished but no Retrogram .xap was found." }
$out = Join-Path $root "out"
New-Item -ItemType Directory -Force -Path $out | Out-Null
Copy-Item $xap.FullName $out -Force
Write-Host "Built $(Join-Path $out $xap.Name)"
